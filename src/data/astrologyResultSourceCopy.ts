/**
 * Type guard verifying whether a value is a recognized AstrologyResultSourceId.
 */
export function isRecognizedResultSourceId(
  value: unknown,
): value is AstrologyResultSourceId {
  return (
    typeof value === 'string' &&
    ASTROLOGY_RESULT_SOURCE_ORDERED_IDS.includes(
      value as AstrologyResultSourceId,
    )
  );
}

/**
 * Astrology Result Source & Precision Copy
 *
 * A typed, content-only dataset of user-facing source, precision, processing,
 * and storage-scope labels for calculated Astrology results:
 * 1. Calculated Chart (`calculated-chart`): Ephemeris math derived from coordinates and time.
 * 2. Optional AI Reflection (`optional-ai-reflection`): Contemplative text synthesized by AI.
 * 3. Date-Only Uncertainty (`date-only-uncertainty`): No supplied time, omitted houses/angles, and lunar uncertainty.
 * 4. Timed-Chart Precision (`timed-chart-precision`): Time-dependent houses, Ascendant, and lunar position.
 * 5. Provider Processing (`provider-processing`): Stateless external computation without user accounts.
 * 6. Local Saved-Copy Scope (`local-saved-scope`): Local device storage isolated completely from dream journals.
 *
 * All wording is strictly provider-neutral, non-predictive, privacy-preserving, and free of guarantees.
 */

export type AstrologyResultSourceId =
  | 'calculated-chart'
  | 'optional-ai-reflection'
  | 'date-only-uncertainty'
  | 'timed-chart-precision'
  | 'provider-processing'
  | 'local-saved-scope';

export type AstrologyResultCategory =
  | 'source'
  | 'precision'
  | 'processing'
  | 'scope';

export interface AstrologyResultSourceItem {
  /** Unique identifier for the source or precision entry */
  id: AstrologyResultSourceId;
  /** Categorical grouping */
  category: AstrologyResultCategory;
  /** Primary display title */
  title: string;
  /** Concise title for compact cards or tab labels */
  shortTitle: string;
  /** Badge label for pill tags or status chips */
  badgeLabel: string;
  /** Single-sentence summary for scannable cards */
  summary: string;
  /** Comprehensive explanatory narrative */
  description: string;
  /** Key bullet points highlighting critical boundaries or distinctions */
  keyTakeaways: readonly string[];
  /** Screen reader accessible description */
  accessibilityLabel: string;
}

export interface AstrologyPrecisionDetail {
  /** Precision identifier */
  id: 'date-only-uncertainty' | 'timed-chart-precision';
  /** Whether exact birth time is incorporated */
  hasExactTime: boolean;
  /** Whether the Ascendant, Midheaven, and houses can be computed */
  hasAscendantAndHouses: boolean;
  /** Short summary of precision level */
  summary: string;
  /** Badge label for status pills */
  badgeLabel: string;
}

export interface AstrologyResultSourceBundle {
  /** Master title for result attribution section */
  title: string;
  /** Subtitle or introductory note */
  subtitle: string;
  /** Master non-predictive disclaimer */
  coreDisclaimer: string;
  /** Map of result source items indexed by id */
  items: Record<AstrologyResultSourceId, AstrologyResultSourceItem>;
  /** Ordered list of item IDs for consistent presentation */
  orderedItemIds: readonly AstrologyResultSourceId[];
}

